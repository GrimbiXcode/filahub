def write_temp(content, suffix):
    handle = tempfile.NamedTemporaryFile(delete=False, suffix=suffix)
    handle.write(content if isinstance(content, bytes) else content.encode())
    handle.close()
    return handle.name


NOW = datetime.datetime(2026, 11, 9, 12, 0, tzinfo=datetime.timezone.utc)


class ReadTest(unittest.TestCase):
    def test_bgcode_mmu3(self):
        path = write_temp(MMU3, ".bgcode")
        name = "Trees_0.25n_0.12mm_PLAPLAPLAPLA_COREONEMMU3_14h32m.bgcode"
        payload = script.build_payload(script.read_metadata(path), name, NOW)
        self.assertEqual(payload["title"], "Trees")
        self.assertEqual(payload["durationMinutes"], 872)
        self.assertEqual(payload["printer"], "COREONEMMU3")
        self.assertEqual(
            [(f["slot"], f["grams"], f["colorHex"], f["vendor"]) for f in payload["filaments"]],
            [
                (0, 26.3, "#3a200b", None),
                (1, 13.47, "#00330c", None),
                (2, 3.47, "#8d8b8f", None),
                (3, 58.33, "#00a700", None),
            ],
        )
        self.assertEqual(payload["filaments"][0]["profileName"], "Polymaker PolyTerra PLA")

    def test_ascii_head_and_tail(self):
        path = write_temp(ASCII, ".gcode")
        payload = script.build_payload(script.read_metadata(path), path, NOW)
        self.assertEqual(payload["durationMinutes"], 4)
        self.assertEqual(
            payload["filaments"],
            [
                {
                    "slot": 0,
                    "grams": 0.75,
                    "filamentType": "PLA",
                    "colorHex": "#1a1a1a",
                    "profileName": "Prusament PLA",
                    "vendor": "Prusa Polymers",
                }
            ],
        )

    def test_bad_checksum(self):
        data = bytearray(MMU3)
        data[30] ^= 0xFF
        path = write_temp(bytes(data), ".bgcode")
        with self.assertRaises(ValueError):
            script.read_metadata(path)

    def test_external_key_is_stable(self):
        a = script.build_payload({}, "x.gcode", NOW)
        b = script.build_payload({}, "x.gcode", NOW)
        self.assertEqual(a["externalKey"], b["externalKey"])
        self.assertTrue(a["externalKey"].startswith("prusaslicer:"))


class SendTest(unittest.TestCase):
    def test_main_delivers_and_never_fails(self):
        received = []

        class Handler(BaseHTTPRequestHandler):
            def do_POST(self):  # noqa: N802
                body = self.rfile.read(int(self.headers["content-length"]))
                received.append((self.path, self.headers["authorization"], json.loads(body)))
                self.send_response(201)
                self.send_header("content-type", "application/json")
                self.end_headers()
                self.wfile.write(b'{"id": 1, "duplicate": false}')

            def log_message(self, *args):
                pass

        server = HTTPServer(("127.0.0.1", 0), Handler)
        thread = threading.Thread(target=server.serve_forever, daemon=True)
        thread.start()
        token = "fh_" + "a" * 43
        os.environ["FILAHUB_URL"] = f"http://127.0.0.1:{server.server_port}"
        os.environ["FILAHUB_TOKEN"] = token
        try:
            path = write_temp(MMU3, ".bgcode")
            self.assertEqual(script.main(["x", path]), 0)
            self.assertEqual(received[0][0], "/api/ingest/print-imports")
            self.assertEqual(received[0][1], f"Bearer {token}")
            self.assertEqual(received[0][2]["source"], "slicer")
            # Server weg: der Export scheitert trotzdem nicht
            server.shutdown()
            server.server_close()
            self.assertEqual(script.main(["x", path]), 0)
        finally:
            del os.environ["FILAHUB_URL"]
            del os.environ["FILAHUB_TOKEN"]


if __name__ == "__main__":
    unittest.main()
