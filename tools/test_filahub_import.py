def block(block_type, data, compression=0):
    raw = data.encode() if isinstance(data, str) else data
    payload = zlib.compress(raw) if compression == 1 else raw
    head = struct.pack("<HHI", block_type, compression, len(raw))
    if compression:
        head += struct.pack("<I", len(payload))
    params = b"\0" * (6 if block_type == 5 else 2)
    body = head + params + payload
    return body + struct.pack("<I", zlib.crc32(body) & 0xFFFFFFFF)


def bgcode(blocks):
    return b"GCDE" + struct.pack("<IH", 1, 1) + b"".join(blocks)


