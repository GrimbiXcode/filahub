import { crc32, deflateSync } from "node:zlib";
import type { ByteSource } from "@contracts/slicerMetadata";

/**
 * Slicer-Dateien für `api/slicerMetadata.test.ts`, im Test gebaut statt als
 * Datei eingecheckt: Die Beispiele aus libbgcode stehen unter einer fremden
 * Lizenz, und echte G-Code-Dateien sind groß. Die Schlüssel und ihre
 * Schreibweise folgen echten Dateien von PrusaSlicer 2.6 und 2.8.
 *
 * Gegengeprüft wird mit einem eigenen CRC32 und Deflate aus `node:zlib` –
 * nicht mit dem Code unter Test.
 */

export type BlockSpec = {
  type: number;
  /** 0 = keine, 1 = Deflate; andere Werte werden roh übernommen */
  compression?: number;
  /** Text der Metadaten (INI) oder rohe Bytes */
  data: string | Uint8Array;
  /** Vorschaubild: 6 Byte Parameter statt 2 */
  params?: Uint8Array;
  /** Gepackte bzw. entpackte Größe im Kopf überschreiben (kaputte Dateien) */
  declaredUncompressed?: number;
  declaredCompressed?: number;
  badChecksum?: boolean;
};

export function buildBgcode(
  blocks: BlockSpec[],
  options: { version?: number; checksumType?: number } = {}
): Uint8Array {
  const checksumType = options.checksumType ?? 1;
  const parts: Uint8Array[] = [];
  const header = Buffer.alloc(10);
  header.write("GCDE", 0, "latin1");
  header.writeUInt32LE(options.version ?? 1, 4);
  header.writeUInt16LE(checksumType, 8);
  parts.push(header);

  for (const block of blocks) {
    const compression = block.compression ?? 0;
    const raw =
      typeof block.data === "string"
        ? Buffer.from(block.data, "utf8")
        : Buffer.from(block.data);
    const data = compression === 1 ? deflateSync(raw) : raw;
    const head = Buffer.alloc(compression === 0 ? 8 : 12);
    head.writeUInt16LE(block.type, 0);
    head.writeUInt16LE(compression, 2);
    head.writeUInt32LE(block.declaredUncompressed ?? raw.length, 4);
    if (compression !== 0)
      head.writeUInt32LE(block.declaredCompressed ?? data.length, 8);
    const params = Buffer.from(
      block.params ?? new Uint8Array(block.type === 5 ? 6 : 2)
    );
    const body = Buffer.concat([head, params, data]);
    parts.push(body);
    if (checksumType === 1) {
      const sum = Buffer.alloc(4);
      sum.writeUInt32LE((crc32(body) ^ (block.badChecksum ? 1 : 0)) >>> 0);
      parts.push(sum);
    }
  }
  return new Uint8Array(Buffer.concat(parts));
}

export const FILE_METADATA = "Producer=PrusaSlicer 2.8.1\n";

export function printerMetadata(lines: Record<string, string>): string {
  return Object.entries({
    printer_model: "MK4S",
    filament_type: "PLA",
    nozzle_diameter: "0.4",
    ...lines,
  })
    .map(([key, value]) => `${key}=${value}\n`)
    .join("");
}

export function iniText(lines: Record<string, string>): string {
  return Object.entries(lines)
    .map(([key, value]) => `${key}=${value}\n`)
    .join("");
}

/** G-Code-Block: Inhalt egal, er darf nur nie gelesen werden */
export function gcodeBlock(bytes: number): BlockSpec {
  return { type: 1, data: new Uint8Array(bytes).fill(0x47) };
}

/**
 * ASCII-G-Code wie von PrusaSlicer: Kopf mit Kennzahlen (seit 2.6), Rumpf,
 * Fuß mit Kennzahlen und Konfigurationsblock.
 */
export function buildGcode(options: {
  head?: Record<string, string>;
  foot?: Record<string, string>;
  config?: Record<string, string>;
  bodyBytes?: number;
  producer?: string;
}): Uint8Array {
  const comment = (lines: Record<string, string> = {}) =>
    Object.entries(lines)
      .map(([key, value]) => `; ${key} = ${value}\n`)
      .join("");
  const line = "G1 X10.123 Y20.456 E0.01234 ; feature\n";
  const body = line.repeat(
    Math.ceil((options.bodyBytes ?? 1000) / line.length)
  );
  const text =
    `; generated by ${options.producer ?? "PrusaSlicer 2.8.1 on 2024-10-21 at 06:38:01 UTC"}\n` +
    comment(options.head) +
    ";\n; thumbnail begin 16x16 8\n; iVBORw0K\n; thumbnail end\n;\n" +
    body +
    comment(options.foot) +
    "\n; prusaslicer_config = begin\n" +
    comment(options.config) +
    "; prusaslicer_config = end\n";
  return new Uint8Array(Buffer.from(text, "utf8"));
}

/** Liest aus einem Puffer und zählt mit, wie viel gelesen wurde */
export function countingSource(bytes: Uint8Array): ByteSource & {
  bytesRead: number;
} {
  const source = {
    size: bytes.length,
    bytesRead: 0,
    read: async (offset: number, length: number) => {
      if (offset < 0 || length < 0 || offset + length > bytes.length)
        throw new Error(`Lesen außerhalb der Datei: ${offset}+${length}`);
      source.bytesRead += length;
      return bytes.subarray(offset, offset + length);
    },
  };
  return source;
}
