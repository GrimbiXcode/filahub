import { describe, expect, it } from "vitest";
import { filamentPrintSettingsSchema } from "@contracts/printSettings";
import {
  PrusaProfileError,
  bestProfileIndex,
  printSettingsFromProfile,
  profileName,
  prusaBundleFromPrintSettings,
  readPrusaProfiles,
} from "@contracts/prusaProfile";

/**
 * Die Werte stammen aus echten Dateien von PrusaSlicer: dem
 * Konfigurationsblock eines G-Codes (Prusament PLA @MK4S, 2.8.1) und einer
 * MMU3-Datei für den Core One (PolyTerra PLA, 2.9.7). Ein Benutzerprofil und
 * „Konfiguration exportieren“ haben dieselbe Form ohne Abschnitte.
 */
const PRUSAMENT_PLA = `# generated by PrusaSlicer 2.8.1 on 2024-10-21 at 06:38:01 UTC
bed_temperature = 60
chamber_minimal_temperature = 0
chamber_temperature = 0
compatible_printers_condition = printer_notes=~/.*MK4S.*/ and nozzle_diameter[0]==0.4
extrusion_multiplier = 1
filament_colour = #FF8000
filament_density = 1.24
filament_max_volumetric_speed = 15
filament_notes = "Affordable filament, manufactured in-house\\nby Josef Prusa"
filament_retract_length = nil
filament_settings_id = "Prusament PLA @MK4S"
filament_type = PLA
filament_vendor = Prusa Polymers
first_layer_bed_temperature = 60
first_layer_temperature = 230
max_fan_speed = 100
min_fan_speed = 70
temperature = 225
`;

const COREONE_MMU3 = `bed_temperature = 60,60,60,60,60
chamber_temperature = 20,20,20,20,20
extrusion_multiplier = 1,1,1,1,1
filament_colour = #FF8000;#FF8000;#FF8000;#FF8000;#FF8000
filament_density = 1.31,1.31,1.31,1.31,1.31
filament_retract_length = nil,nil,nil,nil,nil
filament_settings_id = "Polymaker PolyTerra PLA @COREONE";"Polymaker PolyTerra PLA @COREONE";"Polymaker PolyTerra PLA @COREONE";"Polymaker PolyTerra PLA @COREONE";"Polymaker PolyTerra PLA @COREONE"
filament_type = PLA;PLA;PLA;PLA;PLA
filament_vendor = Polymaker
first_layer_bed_temperature = 60,60,60,60,60
first_layer_temperature = 230,230,230,230,230
max_fan_speed = 100,100,100,100,100
temperature = 220,220,220,220,220
`;

describe("Profile lesen", () => {
  it("liest ein einzelnes Profil", () => {
    const [profile, ...rest] = readPrusaProfiles(PRUSAMENT_PLA);
    expect(rest).toEqual([]);
    expect(profile.name).toBe("Prusament PLA");
    expect(printSettingsFromProfile(profile)).toEqual({
      settings: {
        kind: "filament",
        nozzleMinC: 225,
        nozzleMaxC: 230,
        bedMinC: 60,
        bedMaxC: 60,
        fanPercent: 100,
        flowPercent: 100,
      },
      densityGramsPerLiter: 1240,
      filamentType: "PLA",
      outOfRange: [],
    });
  });

  it("fasst eine MMU mit fünfmal demselben Profil zu einem zusammen", () => {
    const profiles = readPrusaProfiles(COREONE_MMU3);
    expect(profiles).toHaveLength(1);
    expect(profiles[0].name).toBe("Polymaker PolyTerra PLA");
    const { settings, densityGramsPerLiter } = printSettingsFromProfile(
      profiles[0]
    );
    expect(settings).toEqual({
      kind: "filament",
      nozzleMinC: 220,
      nozzleMaxC: 230,
      bedMinC: 60,
      bedMaxC: 60,
      // 20 °C Bauraum heißt beim Core One „nicht heizen“ – entfällt
      fanPercent: 100,
      flowPercent: 100,
    });
    expect(densityGramsPerLiter).toBe(1310);
  });

  it("trennt verschiedene Profile einer Mehrfarb-Konfiguration", () => {
    const profiles =
      readPrusaProfiles(`filament_settings_id = "Prusament PLA @MK4S";"Generic PETG @MK4S"
filament_type = PLA;PETG
temperature = 215,240
first_layer_temperature = 215,235
bed_temperature = 60,90
first_layer_bed_temperature = 60,85
filament_retract_length = nil,0.8
extrusion_multiplier = 1,0.95
`);
    expect(profiles.map(p => p.name)).toEqual([
      "Prusament PLA",
      "Generic PETG",
    ]);
    const petg = printSettingsFromProfile(profiles[1]);
    expect(petg.filamentType).toBe("PETG");
    expect(petg.settings).toMatchObject({
      nozzleMinC: 235,
      nozzleMaxC: 240,
      bedMinC: 85,
      bedMaxC: 90,
      retractionHundredthsMm: 80,
      flowPercent: 95,
    });
    expect(printSettingsFromProfile(profiles[0]).settings).not.toHaveProperty(
      "retractionHundredthsMm"
    );
  });

  it("liest die Filamentprofile eines Konfigurationspakets", () => {
    const bundle = `# generated by PrusaSlicer
[print:0.20mm SPEED @MK4S (Kopie)]
layer_height = 0.2

[filament:*PLA*]
temperature = 999

[filament:Mein PLA]
inherits = Prusament PLA @MK4S
temperature = 210
first_layer_temperature = 215
chamber_temperature = 45

[filament:Mein ASA]
filament_type = ASA
temperature = 260

[printer:Original Prusa MK4S]
temperature = 1

[presets]
filament = Mein PLA
`;
    const profiles = readPrusaProfiles(bundle);
    expect(profiles.map(p => p.name)).toEqual(["Mein PLA", "Mein ASA"]);
    expect(printSettingsFromProfile(profiles[0]).settings).toEqual({
      kind: "filament",
      nozzleMinC: 210,
      nozzleMaxC: 215,
      chamberC: 45,
    });
  });

  it("lässt Werte außerhalb der Bereiche weg und nennt sie", () => {
    const [profile] = readPrusaProfiles(`filament_type = PEEK
temperature = 520
first_layer_temperature = 0
bed_temperature = 0
max_fan_speed = 140
extrusion_multiplier = 2
filament_density = 0
`);
    const imported = printSettingsFromProfile(profile);
    expect(imported.settings).toEqual({ kind: "filament" });
    expect(imported.outOfRange.sort()).toEqual(
      ["fanPercent", "flowPercent", "nozzleMaxC", "nozzleMinC"].sort()
    );
    expect(imported.densityGramsPerLiter).toBeNull();
    // Das Ergebnis besteht das Schema immer
    expect(
      filamentPrintSettingsSchema.safeParse(imported.settings).success
    ).toBe(true);
  });

  it("nimmt Windows-Zeilenenden und ein BOM", () => {
    const [profile] = readPrusaProfiles(
      "﻿filament_type = PLA\r\ntemperature = 215\r\n"
    );
    expect(printSettingsFromProfile(profile).settings.nozzleMaxC).toBe(215);
  });

  it("meldet eine Datei ohne Filamentprofil", () => {
    expect(() => readPrusaProfiles("[print:x]\nlayer_height = 0.2\n")).toThrow(
      PrusaProfileError
    );
    expect(() => readPrusaProfiles("Hallo Welt")).toThrow(PrusaProfileError);
  });

  it("wählt das Profil mit den meisten gemeinsamen Wörtern vor", () => {
    const profiles =
      readPrusaProfiles(`filament_settings_id = "Generic PLA";"Polymaker PolyTerra PLA";"Prusament PETG"
temperature = 215,220,240
`);
    expect(bestProfileIndex(profiles, "PolyTerra PLA Charcoal Black")).toBe(1);
    expect(bestProfileIndex(profiles, "Etwas ganz anderes")).toBe(0);
  });
});

describe("Profil schreiben", () => {
  const input = {
    name: "PolyTerra PLA Charcoal Black",
    manufacturer: "Polymaker",
    materialType: "PLA",
    colorHex: "#1a1a1a",
    densityGramsPerLiter: 1310,
    settings: {
      kind: "filament" as const,
      nozzleMinC: 210,
      nozzleMaxC: 230,
      bedMinC: 55,
      bedMaxC: 60,
      chamberC: 40,
      fanPercent: 100,
      flowPercent: 95,
      retractionHundredthsMm: 80,
      dryingC: 55,
      enclosureRequired: true,
    },
  };

  it("schreibt ein Paket mit einem Filamentprofil", () => {
    const text = prusaBundleFromPrintSettings(input, "aus filahub\nZeile 2");
    expect(text).toBe(`# aus filahub
# Zeile 2

[filament:Polymaker PolyTerra PLA Charcoal Black (filahub)]
filament_type = PLA
filament_vendor = Polymaker
filament_colour = #1A1A1A
filament_density = 1.31
temperature = 220
first_layer_temperature = 230
bed_temperature = 58
first_layer_bed_temperature = 60
chamber_temperature = 40
max_fan_speed = 100
extrusion_multiplier = 0.95
filament_retract_length = 0.8
`);
  });

  it("liest das eigene Paket zurück – innerhalb der ursprünglichen Spanne", () => {
    const [profile] = readPrusaProfiles(
      prusaBundleFromPrintSettings(input, "x")
    );
    const { settings, densityGramsPerLiter } =
      printSettingsFromProfile(profile);
    expect(settings).toEqual({
      kind: "filament",
      nozzleMinC: 220,
      nozzleMaxC: 230,
      bedMinC: 58,
      bedMaxC: 60,
      chamberC: 40,
      fanPercent: 100,
      flowPercent: 95,
      retractionHundredthsMm: 80,
    });
    expect(densityGramsPerLiter).toBe(1310);
  });

  it("schreibt ohne Einstellungen nur die Angaben des Materials", () => {
    const text = prusaBundleFromPrintSettings(
      { ...input, colorHex: null, densityGramsPerLiter: null, settings: null },
      "x"
    );
    expect(text.split("\n").filter(l => l.includes(" = "))).toEqual([
      "filament_type = PLA",
      "filament_vendor = Polymaker",
    ]);
  });

  it("baut einen Profilnamen ohne gefährliche Zeichen", () => {
    expect(
      profileName({ name: "Polymaker PLA", manufacturer: "Polymaker" })
    ).toBe("Polymaker PLA (filahub)");
    expect(
      profileName({ name: 'PLA [neu]\n@MK4/S: "x"', manufacturer: null })
    ).toBe("PLA neu MK4 S x (filahub)");
    expect(profileName({ name: "", manufacturer: null })).toBe(
      "Material (filahub)"
    );
  });
});
