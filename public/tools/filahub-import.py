#!/usr/bin/env python3
"""filahub – Post-Processing-Skript für PrusaSlicer (seit filahub 4.7.0).

Schickt nach jedem Export die Kennzahlen des G-Codes (Gramm je Filament,
Druckzeit, Drucker) ins Eingangsfach von filahub. Dort wird daraus mit einem
Klick ein Druck – erst dann wird abgebucht.

Einrichten (die App zeigt alles unter „Verbindungen“ fertig zum Kopieren):

1. Diese Datei speichern, z. B. ~/filahub-import.py.
2. Daneben eine Datei mit Adresse und Schlüssel anlegen – NICHT in die
   Skriptzeile von PrusaSlicer schreiben: PrusaSlicer legt die ganze
   Konfiguration samt Skriptzeile in jeden G-Code und jedes Projekt, ein
   Schlüssel dort ginge mit jeder geteilten Datei hinaus.

     Linux/macOS: ~/.config/filahub/import.json
     Windows:     %APPDATA%\\filahub\\import.json

     {"url": "https://filahub.example", "token": "fh_…"}

   (Alternativ die Umgebungsvariablen FILAHUB_URL und FILAHUB_TOKEN.)
3. PrusaSlicer → Druckeinstellungen → Ausgabeoptionen →
   Post-Processing-Skripte:

     Linux/macOS: /usr/bin/env python3 /home/ich/filahub-import.py
     Windows:     "C:\\Pfad\\python.exe" "C:\\Users\\ich\\filahub-import.py"

Nur Python-Standardbibliothek. Scheitert das Einliefern, bricht der Export
NICHT ab – ein Slicer, der wegen filahub nicht exportiert, wäre ein Fehler am
falschen Ort. Die Meldung steht dann im Fenster von PrusaSlicer.
"""

import datetime
import hashlib
import json
import os
import re
import struct
import sys
import urllib.error
import urllib.request
import zlib

VERSION = "4.7.0"
HEAD_BYTES = 64 * 1024
TAIL_BYTES = 512 * 1024
MAX_BLOCKS = 256
MAX_METADATA_BYTES = 1024 * 1024


# ---------------------------------------------------------------------------
# G-Code lesen (Gegenstück: contracts/slicerMetadata.ts)
# ---------------------------------------------------------------------------


def read_metadata(path):
    """Schlüssel-Wert-Paare aus ASCII- oder Binär-G-Code."""
    with open(path, "rb") as handle:
        magic = handle.read(4)
        handle.seek(0)
        if magic == b"GCDE":
            return read_bgcode(handle)
        return read_gcode(handle, os.path.getsize(path))


def read_gcode(handle, size):
    meta = {}
    head = handle.read(min(HEAD_BYTES, size)).decode("utf-8", "replace")
    lines = head.splitlines()
    if size > HEAD_BYTES:
        lines = lines[:-1]  # angeschnitten
    parse_comments(lines, meta)
    if size > HEAD_BYTES:
        start = max(HEAD_BYTES, size - TAIL_BYTES)
        handle.seek(start)
        tail = handle.read().decode("utf-8", "replace").splitlines()[1:]
        parse_comments(tail, meta)
    producer = re.search(r"^; generated by (.+?)(?: on \d{4}-|$)", head, re.M)
    if producer:
        meta["\0producer"] = producer.group(1).strip()
    return meta


def parse_comments(lines, meta):
    for line in lines:
        match = re.match(r"^; ([^=;]+?) = (.*)$", line)
        if match:
            meta[match.group(1)] = match.group(2).strip()


def read_bgcode(handle):
    header = handle.read(10)
    _, version, checksum_type = struct.unpack("<4sIH", header)
    if version != 1 or checksum_type > 1:
        raise ValueError("Unbekannte Fassung des Binär-G-Codes")
    checksum_bytes = 4 if checksum_type == 1 else 0
    meta = {}
    for _ in range(MAX_BLOCKS):
        head = handle.read(8)
        if len(head) < 8:
            break
        block_type, compression, uncompressed = struct.unpack("<HHI", head)
        if block_type == 1:  # G-Code: alle Metadaten stehen davor
            break
        size = uncompressed
        raw_head = head
        if compression != 0:
            extra = handle.read(4)
            raw_head += extra
            (size,) = struct.unpack("<I", extra)
        params_size = 6 if block_type == 5 else 2
        if block_type == 5:
            handle.seek(params_size + size + checksum_bytes, 1)
            continue
        if size > MAX_METADATA_BYTES or uncompressed > MAX_METADATA_BYTES:
            raise ValueError("Metadaten-Block zu groß")
        params = handle.read(params_size)
        data = handle.read(size)
        if checksum_bytes:
            (expected,) = struct.unpack("<I", handle.read(4))
            if zlib.crc32(raw_head + params + data) & 0xFFFFFFFF != expected:
                raise ValueError("Prüfsumme stimmt nicht")
        if compression == 1:
            decompressor = zlib.decompressobj()
            data = decompressor.decompress(data, uncompressed)
        elif compression != 0:
            continue
        for line in data.decode("utf-8", "replace").splitlines():
            key, sep, value = line.partition("=")
            if sep:
                meta[key.strip()] = value
    if "Producer" in meta:
        meta["\0producer"] = meta["Producer"]
    return meta


def split_list(value):
    """`"A";"B"` bzw. `A;B` → Liste, leere Einträge als None."""
    if value is None:
        return []
    items, current, quoted, i = [], "", False, 0
    while i < len(value):
        char = value[i]
        if char == '"':
            quoted = not quoted
        elif char == "\\" and quoted and i + 1 < len(value):
            i += 1
            current += value[i]
        elif char == ";" and not quoted:
            items.append(current.strip() or None)
            current = ""
        else:
            current += char
        i += 1
    items.append(current.strip() or None)
    return items


def color(value):
    if value and re.match(r"^#[0-9a-fA-F]{6}$", value.strip()):
        return value.strip().lower()
    return None


def parse_duration(value):
    if not value:
        return None
    units = {"d": 86400, "h": 3600, "m": 60, "s": 1}
    found = re.findall(r"(\d+)\s*([dhms])", value)
    if not found:
        return None
    seconds = sum(int(amount) * units[unit] for amount, unit in found)
    return 0 if seconds == 0 else max(1, round(seconds / 60))


def title_from_name(name):
    base = re.sub(r"^.*[\\/]", "", name)
    base = re.sub(r"\.(b?gcode|bgc|gco|g)$", "", base, flags=re.I)
    stripped = re.sub(r"_\d+(?:\.\d+)?n_\d+(?:\.\d+)?mm_.*$", "", base)
    return (stripped or base or "Druck")[:255]


def build_payload(meta, output_name, now=None):
    now = now or datetime.datetime.now(datetime.timezone.utc)
    grams = [g.strip() for g in meta.get("filament used [g]", "").split(",")]
    types = split_list(meta.get("filament_type"))
    colors = split_list(meta.get("filament_colour"))
    extruder_colors = split_list(meta.get("extruder_colour"))
    profiles = split_list(meta.get("filament_settings_id"))
    vendors = split_list(meta.get("filament_vendor"))
    filaments = []
    for slot, raw in enumerate(grams):
        try:
            value = float(raw)
        except ValueError:
            continue
        if value <= 0 or len(filaments) >= 16:
            continue
        pick = lambda items: items[slot] if slot < len(items) else None
        profile = pick(profiles)
        filaments.append(
            {
                "slot": slot,
                "grams": round(value, 2),
                "filamentType": pick(types),
                "colorHex": color(pick(extruder_colors)) or color(pick(colors)),
                "profileName": re.sub(r"\s*@.*$", "", profile).strip()
                if profile
                else None,
                "vendor": pick(vendors) if len(vendors) > 1 or len(grams) == 1 else None,
            }
        )
    key = hashlib.sha256(
        f"{output_name}|{now.isoformat(timespec='seconds')}".encode()
    ).hexdigest()
    return {
        "source": "slicer",
        "externalKey": f"prusaslicer:{key[:40]}",
        "title": title_from_name(output_name),
        "printedAt": now.isoformat(timespec="seconds"),
        "status": "success",
        "durationMinutes": parse_duration(
            meta.get("estimated printing time (normal mode)")
        ),
        "printer": (meta.get("printer_model") or "")[:100] or None,
        "filaments": filaments,
    }


# ---------------------------------------------------------------------------
# Einliefern
# ---------------------------------------------------------------------------


def config_paths():
    paths = []
    if os.name == "nt" and os.environ.get("APPDATA"):
        paths.append(os.path.join(os.environ["APPDATA"], "filahub", "import.json"))
    paths.append(os.path.expanduser("~/.config/filahub/import.json"))
    return paths


def load_config():
    url = os.environ.get("FILAHUB_URL")
    token = os.environ.get("FILAHUB_TOKEN")
    if url and token:
        return url, token
    for path in config_paths():
        if os.path.exists(path):
            with open(path, encoding="utf-8") as handle:
                data = json.load(handle)
            return data.get("url"), data.get("token")
    return None, None


def send(url, token, payload):
    request = urllib.request.Request(
        url.rstrip("/") + "/api/ingest/print-imports",
        data=json.dumps(payload).encode(),
        method="POST",
        headers={
            "authorization": f"Bearer {token}",
            "content-type": "application/json",
            "user-agent": f"filahub-prusaslicer/{VERSION}",
        },
    )
    try:
        with urllib.request.urlopen(request, timeout=10) as response:
            return response.status, json.loads(response.read() or b"{}")
    except urllib.error.HTTPError as error:
        try:
            body = json.loads(error.read() or b"{}")
        except ValueError:
            body = {}
        return error.code, body


def main(argv):
    if len(argv) < 2:
        print("filahub: kein G-Code übergeben", file=sys.stderr)
        return 0
    path = argv[-1]
    output_name = os.environ.get("SLIC3R_PP_OUTPUT_NAME") or path
    url, token = load_config()
    if not url or not token:
        print(
            "filahub: Adresse/Schlüssel fehlen – siehe ~/.config/filahub/import.json",
            file=sys.stderr,
        )
        return 0
    try:
        payload = build_payload(read_metadata(path), output_name)
        status, body = send(url, token, payload)
    except Exception as error:  # noqa: BLE001 – der Export soll nie scheitern
        print(f"filahub: nicht eingeliefert ({error})", file=sys.stderr)
        return 0
    if status in (200, 201):
        print(f"filahub: „{payload['title']}“ im Eingangsfach", file=sys.stderr)
    else:
        print(
            f"filahub: abgelehnt (HTTP {status}: {body.get('error', '')})",
            file=sys.stderr,
        )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
